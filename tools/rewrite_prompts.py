    out = head_note + CHARACTER_CARD + "\n" + out

    (DST_DIR / "action-10s.md").write_text(out, encoding="utf-8")
    log.append(f"- `prompts/action-10s.md`：{len(src)} → {len(out)} 字符")

    # ================================================== 逐条动作导出
    # 以 "## X" 切分；第 0 段是文件头 + 角色卡 + 通用前缀
    parts = re.split(r"\n(?=## )", out)
    # parts[0]=h1 标题, parts[1]=角色设定卡, parts[2]=通用前缀, parts[3:]=106 个动作
    generic = "\n".join(parts[:3])
    actions = parts[3:]
    assert len(actions) == 106, f"动作数异常：{len(actions)}"
    written = []
    for i, blk in enumerate(actions, 1):
        title = blk.split("\n", 1)[0][3:].strip()
        safe = re.sub(r'[\\/:*?"<>|]', "_", title)
        p = DST_DIR / "actions" / f"{i:03d}-{safe}.txt"
        p.write_text(generic + "\n" + blk.rstrip() + "\n", encoding="utf-8")
        written.append(p)
    log.append(f"- `prompts/actions/`：导出 {len(written)} 个单动作文件"
               f"（每个 = 角色卡 + 通用前缀 + 该动作，平均 {sum(p.stat().st_size for p in written)//len(written)} B）")

    # ================================================== notify-icons.md
    nsrc = (SRC_DIR / "notify-icons.md").read_text(encoding="utf-8")
    nfix = [
        ("头顶呆毛与尾巴尖端距离画布边缘至少保留 10% 安全边距",
         "额前碎发、披风下摆／长发发梢尖端距离画布边缘至少保留 10% 安全边距"),
        ("头顶呆毛微微翘起，身后鲸鱼尾巴轻缓小幅摆动",
         "额前碎发轻轻晃动，披风下摆与长发发梢轻缓小幅摆动"),
        ("头顶呆毛耷拉下来，身后鲸鱼尾巴垂落", "额前碎发垂落，披风下摆与长发发梢无力下垂"),
        ("头顶呆毛竖起，鲸鱼尾巴轻轻翘起", "额前碎发轻轻翘起，披风下摆与长发发梢轻轻扬起"),
        ("头顶呆毛挺立，鲸鱼尾巴保持平稳", "额前碎发安静服帖，披风下摆与长发发梢保持平稳"),
        ("头顶呆毛弯成一个弧度", "额前碎发弯出一个柔和弧度"),
        ("头顶呆毛翘起，上方飘着一个蓝色对勾", "额前碎发轻轻扬起，上方飘着一个蓝色对勾"),
    ]
    nout = apply_rules(nsrc)
    for a, b in nfix:
        nout = nout.replace(a, b)
    nhead = (
        "# 系统通知图标 AI 生成提示词（6 张 · 银白长发少女定制版）\n\n"
        "> 由上游 `dsh-pet/prompts/系统通知图标提示词.md` 改写而来。\n"
        "> 每张都先把下方「角色设定卡」读一遍，再上传 `character/reference.png` 作为角色参考图。\n\n"
        + CHARACTER_CARD + "\n"
    )
    nout = nhead + nout.split("\n", 1)[1].lstrip("\n")
    (DST_DIR / "notify-icons.md").write_text(nout, encoding="utf-8")
    log.append(f"- `prompts/notify-icons.md`：{len(nsrc)} → {len(nout)} 字符")

    # ================================================== 审计
    residual = {}
    for kw in AUDIT_BAD:
        n = out.count(kw)
        if n:
            residual[kw] = n
    log.append(f"- 残留待核词（action-10s.md）：{residual if residual else '无'}")

    # 抽样 diff
    samples = []
    for idx in (1, 9, 20, 29, 33, 106):
        blk = actions[idx - 1]
        t = blk.split("\n", 1)[0]
        lines = [l for l in blk.split("\n") if l.strip() and not l.startswith("#")]
        samples.append(f"### {idx}. {t}\n\n" + "\n".join(lines[:3]) + "\n")

    REPORT.write_text(
        "# 提示词改写审计\n\n" + "\n".join(log) + "\n\n---\n\n## 抽样（改写后）\n\n"
        + "\n".join(samples) + "\n",
        encoding="utf-8")
    print("OK")
    for l in log:
        print(l)


